"""fellowship_turn.py

A HAI chat turn served by the Fellowship tier. The turn is an ORDER TO TOLKIEN (same form as a placed delegate): a Tolkien `llm` order naming no worker, with the conversation as its single task. Tolkien picks a worker (Tolkien box or tablet) from the available rows. Kirk waits on the order's status (never a clock) and reads the answer from the delivered results file.

Constraints:
- Not streamed: the turn lands whole. Status lines are shown meanwhile, but the final answer is atomic.
- Overflow: If the desk cannot serve the turn (held, handed back, refused, failed, or control failed), return None. The caller must serve the next row. This is never an error.
- Cancellation: Cancel the order before returning None to ensure a late answer cannot arrive twice."""
import json
import os
import re
import threading
import time
import uuid

import cancellation
import config
import notes
import ollama_client
import scheduler
import tablet_orders

TASK = "turn"
PRIORITY = 100                      # a live user waits on it: next in the lane (the placed piece's rule)
POLL_S = 0.3
STATUS_EVERY_S = 2.0
HISTORY_PAIRS = 2                   # the priced CHAT1 shape is a bare one-line turn; a little recent context rides along
HISTORY_CHARS = 2000
CHAT1_PAYLOAD = tablet_orders.FOUNDRY_SHARE + "/payloads/map_swarm_code_hard_chat1_v2.py"   # its newest generation
REL_DIR = "campaigns/hai-chat"
ENDED = ("done", "failed", "cancelled", "expired")

PAYLOAD = '''"""HAI work for the Fellowship, generated by fellowship_turn (#34 design s 3): the order's own chat tasks (a turn: ONE,
the conversation); the CHAT1 payload's whole surface (the reply is the answer; its control validates the run)."""
import importlib.util

_s = importlib.util.spec_from_file_location("_chat1", %(chat1)r)
_c = importlib.util.module_from_spec(_s)
_s.loader.exec_module(_c)
globals().update({_k: _v for _k, _v in vars(_c).items() if not _k.startswith("__")})
SUFFIX = ""
TASKS = {_t: {"kind": "chat", "prompt": _p, "checks": ["lambda: len(REPLY.strip()) > 0"]} for _t, _p in %(tasks)r}
EXPERIMENT_TASK_NAMES = tuple(TASKS.keys())
'''


def wants(band):
    """The weighing's first candidate when it is a Fellowship row that can be served - the row carries Tolkien's `order`
    fields (menu_policy stamps them from menu_fill's own builders; a row without them has nothing to fill a spec from)
    - else None. Only the FIRST row: a Fellowship row behind a GPU row loses to that row, as the weighing said."""
    if not band:
        return None
    return band[0] if servable(band[0]) else None


def servable(c):
    """A weighed candidate this door can serve: a Fellowship row carrying Tolkien's `order` fields."""
    return c.get("host") == scheduler.FELLOWSHIP_HOST and bool((c.get("entry") or {}).get("order"))


def render(messages, text=None):
    """Renders the turn as a single prompt containing only the last `HISTORY_PAIRS` dialogue exchanges and the user's last message.
    The system prompt and tools are excluded because this tier was priced on bare text. The `text` argument must contain only
    the user's own words for the current turn, not the full message history including retrieved notes."""
    turns = [m for m in messages or [] if m.get("role") in ("user", "assistant") and (m.get("content") or "").strip()]
    if not turns and not (text or "").strip():
        return ""
    last = turns[-1] if turns and turns[-1]["role"] == "user" else None
    if last is None and not (text or "").strip():
        return (turns[-1].get("content") or "").strip()
    earlier = (turns[:-1] if last is not None else turns)[-2 * HISTORY_PAIRS:]
    lines = ["%s: %s" % ("User" if m["role"] == "user" else "Assistant", (m.get("content") or "").strip())
             for m in earlier]
    context = "\n".join(lines)
    if len(context) > HISTORY_CHARS:
        context = context[-HISTORY_CHARS:]
    text = (text or "").strip() or (last.get("content") or "").strip()
    if not context:
        return text
    return "Earlier in this conversation:\n%s\n\nUser: %s" % (context, text)


def today_line():
    """One line naming today's date for the Fellowship's model, which gets no system prompt (the row is priced bare)."""
    return "(Today is %s.)\n\n" % time.strftime("%A, %B %d, %Y").replace(" 0", " ")


def payload_text(prompt):
    return payload_tasks_text([(TASK, prompt)])


def payload_tasks_text(tasks):
    """The generated Fellowship payload for several chat tasks [(name, prompt), ...] in order - a turn has one; a batch
    order (claim_sweep's review) one per item. Everything else is the CHAT1 payload's surface, its control included."""
    return PAYLOAD % {"chat1": CHAT1_PAYLOAD, "tasks": [(str(t), str(p)) for t, p in tasks]}


def _paths(name):
    rel = "%s/%s" % (REL_DIR, time.strftime("%Y%m%d"))
    local = os.path.join(tablet_orders.SHARE, *rel.split("/"))
    foundry = "%s/%s" % (tablet_orders.FOUNDRY_SHARE, rel)
    return local, foundry, name + ".payload.py", name + ".results.json"


def order_bodies(q, prompt, family, tier, interactive, priority=PRIORITY):
    """(FactoryOrderReq kwargs, local results path): the Fellowship form (a Tolkien `llm` order naming no worker; the
    desk adds `placement`), pinned to the Fellowship (`only`), beside the GPU template the desk requires of every order
    (never placed here - a GPU row would have won the weighing instead)."""
    user = re.sub(r"[^A-Za-z0-9]+", "-", str(getattr(q, "user", "") or "hai")).strip("-")[:16].lower()
    chat = str(getattr(q, "chat_id", "") or "")[:8]
    name = "hai-fel-%s-%s-%s-%s" % (user, chat or "x", time.strftime("%Y%m%d-%H%M%S"), uuid.uuid4().hex[:4])
    local, foundry, payload, result = _paths(name)
    os.makedirs(local, exist_ok=True)
    tmp = os.path.join(local, payload + ".tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(payload_text(prompt))
    os.replace(tmp, os.path.join(local, payload))
    fel_spec = {"kind": "llm", "name": name, "payload": foundry + "/" + payload, "tasks": [TASK], "replicates": 1,
                "priority": priority, "notify": "failures", "deliver_to": foundry + "/" + result, "initiator": "hai",
                # the user's bare words, for McCoy's advice to Tolkien (shadow) - the payload carries the turn itself
                "request": prompt[:1500]}
    items = os.path.join(local, name + ".items.json")
    with open(items, "w", encoding="utf-8") as f:
        json.dump({"items": [{"id": TASK, "prompt": prompt}]}, f)
    gpu_spec = {"name": name, "mode": "compute", "load": "gpu", "initiator": "hai",
                "payload": "{FOUNDRY_ROOT}\\bin\\infer_ollama.py",
                "args": [items, "{ORDER_OUT}\\out.json", "--model", "{POLICY_MODEL}", "--rounds", "1",
                         "--num-ctx", "{POLICY_NUM_CTX}", "{POLICY_TEMPERATURE_ARGS}", "--seed-base", "1",
                         "{POLICY_THINK_ARGS}"],
                "progress_glob": "{ORDER_OUT}\\out.progress\\*.done", "progress_total": 1,
                "deliver_to": foundry, "notify": "failures", "priority": priority}
    body = {"spec": gpu_spec, "requires": ["order.compute"], "family": family, "tier": tier,
            "lens": "fastest" if interactive else "least_energy", "only": [scheduler.FELLOWSHIP_HOST],
            "fellowship": {"spec": fel_spec, "requires": ["fellowship.placed"]}, "rush": True}
    return body, os.path.join(local, result), name


def _desk():
    import app                              # the same in-process doors every order uses (chat_window._intake's precedent)
    return app


def submit(q, prompt, family, tier, interactive, desk=None, priority=PRIORITY):
    """-> (order id, local results path, name) or (None, why, name): the desk's reply, read as the placed delegate reads
    it. A hold is cancelled at once (a chat turn does not wait in line behind a box the weighing can route around)."""
    app = desk or _desk()
    body, result, name = order_bodies(q, prompt, family, tier, interactive, priority=priority)
    try:
        reply = app.p20_order(app.FactoryOrderReq(**dict(body, user=str(getattr(q, "user", "") or "hai"))))
    except Exception as exc:                                        # noqa: BLE001 - the next row serves the turn
        return None, "the desk refused the Fellowship turn: %r" % (exc,), name
    if reply.get("held"):
        cancel(reply.get("id"), "a chat turn routes around a held Fellowship", app)
        return None, "held: %s" % "; ".join(reply.get("why") or []), name
    steps = [s for s in (reply.get("steps") or []) if isinstance(s, dict)]
    if not reply.get("ok") or len(steps) != 1 or steps[0].get("host") != scheduler.FELLOWSHIP_HOST:
        return None, "not placed on the Fellowship: %s" % (reply.get("error") or "; ".join(reply.get("why") or [])
                                                            or str(reply)[:160]), name
    return steps[0]["id"], result, name


def cancel(order_id, why, desk=None):
    if not order_id:
        return
    app = desk or _desk()
    try:
        app.p20_order_cancel(app.OrderCancelReq(id=order_id, why=why, source="hai-fellowship-turn"))
    except Exception as exc:                                        # noqa: BLE001
        notes.log("FELLOWSHIP TURN could not cancel %s: %r" % (order_id, exc))


def read_answer(result_path):
    """The answer in the delivered results file, or (None, why). The run's control must have passed (the lab's rule: a
    failed control voids the delivery) and the turn's row must have an answer."""
    try:
        with open(result_path, encoding="utf-8") as f:
            res = json.load(f)
    except (OSError, ValueError) as exc:
        return None, "results unreadable: %r" % (exc,), {}
    if not res.get("control_passed"):
        return None, "the run's control did not pass", res
    row = next((r for r in res.get("rows") or [] if r.get("task") == TASK), None)
    if row is None:
        return None, "no %s row in the delivery" % TASK, res
    ans = (row.get("answer") or "").strip()
    if not ans:
        return None, "an empty answer", res
    return ans, None, dict(res, row=row)


def wait(order_id, result_path, status=None, desk=None, clock=time.time, sleep=time.sleep):
    """Wait on the ORDER'S STATUS (the desk's own record, in-process) until it ends: done -> the delivered answer;
    failed / cancelled / expired / held again -> None (the next row serves the turn); the user's Stop -> cancel + None.
    No clock ends it: a live order is working until the desk says otherwise (the factory's own lifecycle reports a dead
    worker). -> (answer or None, why or None, info)."""
    app = desk or _desk()
    last_status, started = 0.0, clock()
    while True:
        if cancellation.is_cancelled():
            cancel(order_id, "the user stopped the turn", app)
            return None, "stopped by the user", {}
        view = app._order_status_view(order_id) or {}
        st = view.get("status")
        if st == "done":
            ans, why, info = read_answer(result_path)
            info["wall_s"] = round(clock() - started, 2)
            return ans, why, info
        if st in ENDED or st == "held":
            if st == "held":
                cancel(order_id, "handed back - the next row serves the turn", app)
            return None, "the order ended %s%s" % (st, (": " + str(view.get("reason") or view.get("hold_reason")))
                                                   if (view.get("reason") or view.get("hold_reason")) else ""), {}
        if status and clock() - last_status >= STATUS_EVERY_S:
            last_status = clock()
            status("The Fellowship is answering (Tolkien, order %s, %s)" % (view.get("order") or order_id, st or "queued"))
        sleep(POLL_S)


_IN_FLIGHT = set()               # desk ids of HAI turns placed on the Fellowship and not ended yet
_IN_FLIGHT_LK = threading.Lock()


def in_flight():
    """How many HAI turns Kirk has on the Fellowship right now, unanswered - Spock's weighing reads it
    (scheduler.FELLOWSHIP_PENDING): a burst of turns placed in the same second is a line before Tolkien has collected
    any of it. Registered inside the one door every Fellowship turn crosses (answer_turn), never by each caller."""
    with _IN_FLIGHT_LK:
        return len(_IN_FLIGHT)


scheduler.FELLOWSHIP_PENDING[0] = in_flight


def answer_turn(q, messages, cand, family, tier, interactive, status=None, desk=None, text=None, priority=PRIORITY):
    """The whole turn on the Fellowship -> {"answer", "label", "model", "order", "wall_s", "worker"} or None (the caller
    serves the next row). `cand` is the weighing's Fellowship candidate (wants()); `text` the user's bare words (render)."""
    token = object()                 # counted from the moment it enters the door: the weighing of a turn a second behind
    with _IN_FLIGHT_LK:              # sees it before the desk has even answered
        _IN_FLIGHT.add(token)
    try:
        return _answer_turn(q, messages, cand, family, tier, interactive, status, desk, text, priority)
    finally:
        with _IN_FLIGHT_LK:
            _IN_FLIGHT.discard(token)


def _answer_turn(q, messages, cand, family, tier, interactive, status, desk, text, priority):
    # Include today's date so the model can answer time-sensitive queries; small models often hallucinate the year if it is omitted
    prompt = today_line() + render(messages, text)
    if not prompt:
        return None
    row = cand.get("entry") or {}
    oid, result, name = submit(q, prompt, family, tier, interactive, desk=desk, priority=priority)
    if not oid:
        notes.log("FELLOWSHIP TURN not served (%s) - the next row serves it: %s" % (name, result))
        return None
    notes.log("FELLOWSHIP TURN %s placed (desk %s): %s/%s row %s %s, %.1f s/solve, %s" % (
        name, oid, family, tier, cand.get("box"), row.get("model"), float(cand.get("time_s") or 0),
        ("%.0f J" % cand["j"]) if cand.get("j") is not None else "J unmetered"))
    if status:
        status("Spock placed this on the Fellowship (%s %s) - Tolkien is answering" % (cand.get("box"), row.get("model")))
    ans, why, info = wait(oid, result, status=status, desk=desk)
    if ans is None:
        notes.log("FELLOWSHIP TURN %s not answered (%s) - the next row serves it" % (name, why))
        return None
    r = info.get("row") or {}
    worker = r.get("_host") or r.get("node") or r.get("arm") or cand.get("box")
    notes.log("FELLOWSHIP TURN %s answered by %s in %.1f s (%s chars, %s tok/s)" % (
        name, worker, info.get("wall_s") or 0, len(ans), r.get("gen_tps")))
    return {"answer": ans, "label": "Fellowship %s %s (weighed %s/%s)" % (worker, row.get("model"), family, tier),
            "model": row.get("model"), "order": oid, "name": name, "wall_s": info.get("wall_s"), "worker": worker}
