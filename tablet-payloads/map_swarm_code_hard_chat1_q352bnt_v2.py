# ---------------------- Staging (SPEC §6 — reuse gauntlet pattern)

def _remote_mb(model):
    try:
        req = urllib.request.Request("%s/%s.gguf" % (STAGE_URL, model), method="HEAD")
        with urllib.request.urlopen(req, timeout=20) as r:
            cl = r.headers.get("Content-Length")
            return int(cl) / (1024 * 1024) if cl else None
    except Exception:
        return None


def _evict_pulled(need_mb):
    try:
        pulled = [f for f in os.listdir(LLM_DIR)
                  if f.endswith(".gguf") and os.path.exists(os.path.join(LLM_DIR, f + ".pulled"))]
    except FileNotFoundError:
        return
    pulled.sort(key=lambda f: os.path.getsize(os.path.join(LLM_DIR, f)), reverse=True)
    for f in pulled:
        if _free_mb() >= need_mb:
            break
        for x in (f, f + ".pulled"):
            try:
                os.remove(os.path.join(LLM_DIR, x))
            except OSError:
                pass


def stage_model(model):
    path = os.path.join(LLM_DIR, model + ".gguf")
    if os.path.exists(path):
        return path, None
    if not STAGE_URL:
        return None, "staging_failed:no_stage_url"
    need = _remote_mb(model)
    if need is None:
        return None, "staging_failed:model_not_in_store"
    if _free_mb() < need + KEEP_FREE_MB:
        _evict_pulled(need + KEEP_FREE_MB)
    if _free_mb() < need + KEEP_FREE_MB:
        return None, "staging_failed:model_too_big_for_node"
    tmp = path + ".part"
    try:
        with urllib.request.urlopen("%s/%s.gguf" % (STAGE_URL, model), timeout=1200) as r, \
                open(tmp, "wb") as f:
            shutil.copyfileobj(r, f, 1024 * 1024)
    except Exception:
        try:
            os.remove(tmp)
        except OSError:
            pass
        return None, "staging_failed:transfer_failed"
    if os.path.exists(tmp) and os.path.getsize(tmp) > 1_000_000:
        os.replace(tmp, path)
        try:
            open(path + ".pulled", "w").close()
        except OSError:
            pass
        return path, None
    try:
        os.remove(tmp)
    except OSError:
        pass
    return None, "staging_failed:transfer_short"


# ---------------------- Inference (argv-only; prompt via -f file, never a shell)

IDLE_S = 120          # CPU time frozen this long = llama-cli has stopped working (not a budget on the answer)
IDLE_POLL_S = 5


def _cpu_ticks(pid):
    try:
        with open("/proc/%d/stat" % pid) as f:
            fields = f.read().rsplit(")", 1)[1].split()
        return int(fields[11]) + int(fields[12])      # utime + stime
    except Exception:
        return None


# a loop is no progress either (13a): the same rule and constants as infer_ollama.looping / tolkien_llm.looping
LOOP_WINDOW, LOOP_RATIO = 4000, 0.10
_LOOPED = [False]


def looping(tail):
    if len(tail) < 2 * LOOP_WINDOW:
        return False
    import re, zlib

    def r(s):
        b = re.sub(r"\d+", "0", s).encode("utf-8", "replace")
        return len(zlib.compress(b, 9)) / len(b)
    return r(tail[-LOOP_WINDOW:]) < LOOP_RATIO and r(tail[-2 * LOOP_WINDOW:-LOOP_WINDOW]) < LOOP_RATIO


def _output_tail(out_path):
    """The last 2 * LOOP_WINDOW chars of what the model has written. NUL bytes are dropped: on some tablets (merry,
    pippin) llama-cli's output file reads as thousands of NULs while the model loads - padding, not text, and it
    compresses like a perfect loop."""
    try:
        with open(out_path, "rb") as f:
            f.seek(0, 2)
            f.seek(max(0, f.tell() - 64 * LOOP_WINDOW))
            return f.read().replace(b"\x00", b"").decode("utf-8", "replace")[-2 * LOOP_WINDOW:]
    except OSError:
        return ""


def _run_until_idle(argv, env, cwd, out_path):
    """Run argv with stdout to out_path; end it only when its CPU time stops moving for IDLE_S, or its output loops.
    Returns (returncode or None, None | "stalled" | "loop")."""
    with open(out_path, "wb") as out:
        proc = subprocess.Popen(argv, stdout=out, stderr=subprocess.DEVNULL, stdin=subprocess.DEVNULL,
                                env=env, cwd=cwd)
        last, still_since = None, time.time()
        while proc.poll() is None:
            # wait ON the process, not a flat sleep: an exit is seen at once, so the row's wall is the generation's
            # own time
            try:
                proc.wait(timeout=IDLE_POLL_S)
                break
            except subprocess.TimeoutExpired:
                pass
            if looping(_output_tail(out_path)):
                proc.kill()
                proc.wait()
                return None, "loop"
            ticks = _cpu_ticks(proc.pid)
            if ticks is None or ticks != last:
                last, still_since = ticks, time.time()
            elif time.time() - still_since >= IDLE_S:
                proc.kill()
                proc.wait()
                return None, "stalled"
        return proc.returncode, None


def process_item(*args, **kwargs):
    """The row says `finish_reason: "loop"` whichever path it took when its generation was cut as a loop."""
    _LOOPED[0] = False
    row = _process_item_inner(*args, **kwargs)
    if _LOOPED[0] and isinstance(row, dict):
        row["finish_reason"] = "loop"
    return row


def run_llama(model_basename, prompt, seed, prompt_path):
    """Argv-based llama-cli invocation. Prompt bytes flow through -f, not a shell.
    Returns (stdout_or_None, wall_s, error_or_None)."""
    with open(prompt_path, "w", encoding="utf-8") as f:
        f.write(prompt)
    env = dict(os.environ)
    env["LD_LIBRARY_PATH"] = LLM_DIR
    argv = [
        LLAMA_CLI,
        "-m", os.path.join(LLM_DIR, model_basename + ".gguf"),
        "-f", prompt_path,
        "-st", "--no-display-prompt", "-rea", "off",
        "--temp", str(TEMPERATURE),
        "--seed", str(seed),
        "-n", str(TOKEN_LIMIT),
        "-c", str(CONTEXT),
        "-t", str(THREADS),
    ]
    t0 = time.time()
    out_path = prompt_path + ".out"
    try:
        rc, why = _run_until_idle(argv, env, LLM_DIR, out_path)
    except FileNotFoundError:
        return None, round(time.time() - t0, 1), "llama_cli_missing"
    wall = round(time.time() - t0, 1)
    with open(out_path, "rb") as f:
        stdout = f.read().decode(errors="replace")
    if why == "stalled":
        return None, wall, "generation_stalled"
    if why == "loop":
        # the model's answer is what it wrote before the cut: close it the way llama-cli would, so it is graded
        _LOOPED[0] = True
        stdout += LLAMA_CLI_STATS + " cut: output looping ]\n"
    return stdout, wall, None


# ---------------------- Extraction (matches rigby extract_code semantics)

def extract_code(text):
    m = re.search(r"```(?:python)?[^\n]*\n(.*?)```", text, re.DOTALL)
    if m:
        return m.group(1)
    text = text.split("<|im_end|>")[0]
    m = re.search(r"(?:^|\n)(def |import |from )", text)
    return text[m.start():] if m else text


# ---------------------- Scoring (bounded child process; never raises)

def score(code, checks, work_dir):
    """Run generated code + fixed check lambdas in a separate python3 process.
    Returns (passed:int, total:int, err:str). Never raises."""
    lambdas = ", ".join(checks)
    prog = (
        code + "\n\n__cnt=0;__tot=0\n"
        "def _ck(f):\n    global __cnt,__tot\n    __tot+=1\n"
        "    try:\n        if f() is True or f()==True: __cnt+=1\n"
        "    except Exception: pass\n"
        "for _f in [" + lambdas + "]:\n    _ck(_f)\n"
        'print("RESULT",__cnt,__tot)\n'
    )
    total = len(checks)
    # GNU `timeout` is a coreutil present on Termux/Linux (production target).
    # Windows has `timeout.exe` with different, INTERACTIVE semantics — never
    # invoke it here. Fall back to parent-only enforcement on Windows / when
    # the binary is absent.
    argv_timeout = ["timeout", str(SCORE_CHILD_TIMEOUT_S), "python3", "-"]
    argv_direct = ["python3", "-"]
    r = None
    if os.name != "nt":
        try:
            r = subprocess.run(argv_timeout, capture_output=True, input=prog.encode("utf-8"),
                               cwd=work_dir, timeout=SCORE_PARENT_TIMEOUT_S)
        except subprocess.TimeoutExpired:
            return 0, total, "score_parent_timeout"
        except FileNotFoundError:
            r = None  # fall through
    if r is None:
        try:
            r = subprocess.run(argv_direct, capture_output=True, input=prog.encode("utf-8"),
                               cwd=work_dir, timeout=SCORE_PARENT_TIMEOUT_S)
        except subprocess.TimeoutExpired:
            return 0, total, "score_parent_timeout"
        except FileNotFoundError:
            return 0, total, "python3_missing"
    m = re.search(r"RESULT (\d+) (\d+)", r.stdout.decode(errors="replace"))
    if m:
        return int(m.group(1)), int(m.group(2)), ""
    stderr_tail = (r.stderr.decode(errors="replace").strip().splitlines() or [""])[-1][:160]
    return 0, total, stderr_tail or "no_result_line"


# ---------------------- Row assembly (SPEC §5)

_ROW_KEYS_REQUIRED = (
    "item", "arm", "task", "replicate", "seed", "model", "temperature", "token_limit",
    "ran", "ok", "checks_passed", "checks_total", "wall_s", "error", "answer",
)


def _base_row(item, arm, task, replicate, seed, model):
    return {
        "item": item,
        "arm": arm,
        "task": task,
        "replicate": replicate,
        "seed": seed,
        "model": model,
        "temperature": TEMPERATURE,
        "token_limit": TOKEN_LIMIT,
        "ran": False,
        "ok": False,
        "checks_passed": 0,
        "checks_total": 0,
        "wall_s": 0.0,
        "error": "",
        "answer": "",
    }


def _fail_row(item, arm, task, replicate, seed, model, err, wall=0.0):
    row = _base_row(item, arm, task, replicate, seed, model)
    row["error"] = err
    row["wall_s"] = wall
    return row


def _bad_item_row(item, err):
    row = _base_row(item, "", "", 0, 0, "")
    row["error"] = err
    return row


_SENTINEL_ANY_CASE_RE = re.compile(re.escape(CONTROL_SENTINEL), re.IGNORECASE)


def _redact_sentinel(text):
    """Case-INSENSITIVE redaction — foundry's validate_control lowercases the
    whole row JSON before substring match (tablet_fulfil.py line 330), so a
    model emitting `Code_Control_Pass` (any case variant) in its answer would
    silently trigger a control pass without this."""
    if not text:
        return text
    return _SENTINEL_ANY_CASE_RE.sub("[REDACTED_SENTINEL]", text)


def _payload_item(item):
    """Remove Tolkien's existing SKU-lane routing prefix while preserving the coverage key."""
    lane, marker, body = item.partition("~")
    return body if marker and lane in {"A", "B", "C", "sam"} else item


# ---------------------- Answer boundary (generated from cli_answer.py - measured; see its docstring)
LLAMA_CLI_ECHO_LIMIT = 500
LLAMA_CLI_TRUNCATED = ' ... (truncated)\n'
LLAMA_CLI_STATS = '\n\n[ Prompt:'


def llama_cli_answer(stdout, prompt):
    end = stdout.rfind(LLAMA_CLI_STATS)
    if end < 0:
        return None, "answer_boundary:stats_line_missing"
    echo = "\n> " + prompt[:LLAMA_CLI_ECHO_LIMIT]
    n = stdout.count(echo, 0, end)
    if n != 1:
        return None, "answer_boundary:prompt_echo_found_%d_times" % n
    i = stdout.find(echo) + len(echo)
    tail = LLAMA_CLI_TRUNCATED if len(prompt) > LLAMA_CLI_ECHO_LIMIT else "\n"
    if not stdout.startswith(tail, i):
        return None, "answer_boundary:prompt_echo_end_unrecognised"
    return stdout[i + len(tail):end].strip("\n"), ""


def mtmd_answer(stdout):
    answer = stdout.strip()
    if not answer:
        return None, "answer_boundary:empty_stdout"
    return answer, ""



def _process_item_inner(item, prompt_path, work_dir):
    arm, task, replicate, seed, model, perr = parse_item(_payload_item(item))
    if perr is not None:
        return _bad_item_row(item, perr)

    e = check_arch()
    if e:
        return _fail_row(item, arm, task, replicate, seed, model, e)
    e = check_ram()
    if e:
        return _fail_row(item, arm, task, replicate, seed, model, e)
    e = ensure_llm_dir()
    if e:
        return _fail_row(item, arm, task, replicate, seed, model, e)
    e = check_disk()
    if e:
        return _fail_row(item, arm, task, replicate, seed, model, e)

    _path, staging_err = stage_model(model)
    if staging_err:
        return _fail_row(item, arm, task, replicate, seed, model, staging_err)

    tdef = CONTROL_TASKS[task] if arm == ARM_CONTROL else TASKS[task]
    prompt = tdef["prompt"] + SUFFIX
    stdout, wall, err = run_llama(model, prompt, seed, prompt_path)
    if err is not None:
        return _fail_row(item, arm, task, replicate, seed, model, err, wall=wall)

    answer, aerr = llama_cli_answer(stdout, prompt)
    if aerr:
        row = _fail_row(item, arm, task, replicate, seed, model, aerr, wall=wall)
        row["raw_stdout"] = _redact_sentinel(stdout)
        return row
    code = extract_code(answer)
    if not code.strip():
        row = _fail_row(item, arm, task, replicate, seed, model, "no_code_extracted", wall=wall)
        row["answer"] = _redact_sentinel(answer)
        return row

    passed, total, serr = score(code, tdef["checks"], work_dir)
    row = _base_row(item, arm, task, replicate, seed, model)
    row["wall_s"] = wall
    row["ran"] = True
    row["checks_passed"] = passed
    row["checks_total"] = total
    row["ok"] = (total > 0 and passed == total)
    row["error"] = _redact_sentinel(serr)
    row["answer"] = _redact_sentinel(answer)
    row["code"] = _redact_sentinel(code)

    if arm == ARM_CONTROL and row["ok"] and row["checks_passed"] == row["checks_total"] and total > 0:
        row["control_result"] = CONTROL_SENTINEL

    return row


