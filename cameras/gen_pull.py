"""Fuzzy-dedupe night_clips.tsv (main/sub spans differ by ~1 s) and emit pull_replay.sh —
parallel -c copy pulls (no decode) from NVR playback into the frigate container.

Dedupe: same channel + same start second -> keep the LONGER end. Windows are the clip's own
span (already contiguous per NVR indexing; adjacent [R] footage not wanted).
Concurrency 6 (measured 4->4x, 10->7-9.3x; 6 is polite). Shell is dash: no arithmetic,
hardcoded commands, one wait per batch.
"""
import sys
from datetime import datetime

from nvr_settings import rtsp

if len(sys.argv) != 3:
    sys.exit("usage: gen_pull.py <night_clips.tsv> <pull_replay.sh>")

rows = {}
with open(sys.argv[1], encoding="utf-8") as f:
    for line in f:
        parts = line.strip().split("\t")
        if len(parts) != 4:
            continue
        ch, st, en, dur = parts
        key = (ch, st)
        if key not in rows or en > rows[key]:
            rows[key] = en

jobs = []
for (ch, st), en in sorted(rows.items()):
    t0 = datetime.strptime(st, "%Y-%m-%d %H:%M:%S")
    t1 = datetime.strptime(en, "%Y-%m-%d %H:%M:%S")
    name = "ch%s_%s" % (ch, t0.strftime("%H%M%S"))
    jobs.append((ch, t0.strftime("%Y_%m_%d_%H_%M_%S"), t1.strftime("%Y_%m_%d_%H_%M_%S"),
                 name, int((t1 - t0).total_seconds())))

total = sum(j[4] for j in jobs)
print("clips after fuzzy dedupe: %d, total %.1f min" % (len(jobs), total / 60))

lines = [
    "#!/bin/sh",
    "# Parallel -c copy pull of last night's [M] clips (generated by gen_pull.py).",
    "set -u",
    "FF=/usr/lib/ffmpeg/5.0/bin/ffmpeg",
    "mkdir -p /tmp/replay",
    ": > /tmp/replay/_pull.log",
]
BATCH = 6
for i in range(0, len(jobs), BATCH):
    for ch, s, e, name, dur in jobs[i:i + BATCH]:
        url = (rtsp() + "/cam/playback"
               "?channel=%s&starttime=%s&endtime=%s" % (ch, s, e))
        to = dur + 90
        lines.append(
            'timeout %d "$FF" -hide_banner -loglevel error -rtsp_transport tcp '
            '-i "%s" -c copy -an -y /tmp/replay/%s.mp4 >>/tmp/replay/_pull.log 2>&1 &'
            % (to, url, name))
    lines.append("wait")
lines.append('ls /tmp/replay/*.mp4 | wc -l')
lines.append('echo PULL_DONE')

out = sys.argv[2]
with open(out, "w", newline="\n", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print("wrote pull_replay.sh with %d jobs in batches of %d" % (len(jobs), BATCH))
