"""Generate map_vlm_swarm_hard.py from the frozen map_vlm_swarm.py: same staging, runtime, scorer and row
contract; changes are (1) the SAMPLING KNOB - llama-mtmd-cli runs `--temp VLM_TEMPERATURE --seed <item seed>`
instead of the frozen `--temp 0` (greedy made every replicate identical, so a per-task pass RATE and any vote
were meaningless), (2) the task pool is hard_vlm_tasks.TASKS, (3) the experiment arm is `vlm-hard`, and
(4) the control cell n_number moves to its own table so it can never be dealt as an experiment task.
The frozen payload is never edited (one name = one artifact; Phase 5 manifests pin its sha).

Positive control: import the generated payload and drive run_vlm_cell/main with `sh` and staging stubbed -
the command must carry the knob and the item's seed, gold must score ok, the distractor must not, the
control must emit its sentinel, and a bad seed/arm must be refused.
    python gen_vlm_hard_payload.py [--temp 0.6]
"""
import hashlib, importlib.util, json, os, pathlib, pprint, py_compile, re, subprocess, sys, tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import hard_vlm_tasks  # noqa: E402
import menu_paths as MP  # noqa: E402  the payload folder and the mirrors are settings
import task_versions as TV  # noqa: E402  which generation of a template is current

SRC = pathlib.Path(MP.need("PAYLOADS")) / TV.newest_payload("map_vlm_swarm.py")
# One payload name per serve scale: 2x keeps the name its manifests pin; any other scale gets its own file.
DST = pathlib.Path(MP.need("PAYLOADS")) / (
    "map_vlm_swarm_hard.py" if hard_vlm_tasks.SERVE_SCALE == 2 else "map_vlm_swarm_hard_%dx.py" % hard_vlm_tasks.SERVE_SCALE)
_argv = sys.argv[1:]
TEMP = float(_argv[_argv.index("--temp") + 1]) if "--temp" in _argv else 0.6
ARM = "vlm-hard"


def sub1(text, old, new):
    assert text.count(old) == 1, "expected exactly one %r, found %d" % (old[:60], text.count(old))
    return text.replace(old, new, 1)


src = SRC.read_text(encoding="utf-8")
assert "\r" not in src
m = re.search(r"^VLM_TASKS = \{\n.*?^\}\n", src, re.S | re.M)
assert m, "VLM_TASKS block not found"
ctrl = re.search(r'^    "n_number": \(.*\),$', m.group(0), re.M)
assert ctrl, "n_number control cell not found in the frozen table"
block = ("VLM_TEMPERATURE = %r  # Hard Bench sampling knob (spec: every division ~0.6, seed = replicate + 1)\n"
         "VLM_TASKS = %s\n"
         "# The control cell, kept out of VLM_TASKS so it can never be dealt as an experiment task.\n"
         "VLM_CONTROL_TASKS = {\n%s\n}\n"
         "_VLM_ALL = {**VLM_TASKS, **VLM_CONTROL_TASKS}\n"
         % (TEMP, pprint.pformat(hard_vlm_tasks.TASKS, width=150, sort_dicts=False), ctrl.group(0)))
out = src[:m.start()] + block + src[m.end():]
out = sub1(out, "    img = VLM_TASKS[taskid][0]\n", "    img = _VLM_ALL[taskid][0]\n")
out = sub1(out, "def run_vlm_cell(model, taskid):\n", "def run_vlm_cell(model, taskid, seed=1):\n")
out = sub1(out, "    _img, question, expected, match, category = VLM_TASKS[taskid]\n",
           "    _img, question, expected, match, category = _VLM_ALL[taskid]\n")
out = sub1(out, '"-p %s -n 32 --temp 0 -c 2048 -t 8" %', '"-p %s -n 32 --temp %s --seed %d -c 2048 -t 8" %')
out = sub1(out, "shlex.quote(image_path), shlex.quote(question)))",
           "shlex.quote(image_path), shlex.quote(question), VLM_TEMPERATURE, seed))")
# Measured (cli_answer.py): llama-mtmd-cli's stdout IS the answer - read all of it, not its first line, and store
# it whole; an empty stdout is an instrument failure, not a wrong answer.
import payload_embed  # noqa: E402
out = payload_embed.embed(out, "\ndef run_vlm_cell(")
out = sub1(out, '    ans = next((line.strip() for line in out.splitlines() if line.strip()), out)\n',
           '    ans, aerr = mtmd_answer(out)\n'
           '    if aerr:\n'
           '        return {"ran": False, "reason": aerr, "ok": None, "wall_s": wall, "category": category, "raw_stdout": out}\n')
out = sub1(out, '    return {"ran": True, "ok": _vlm_score(ans, expected, match), "wall_s": wall,',
           '    return {"ran": True, "ok": _vlm_score(ans, expected, match), "wall_s": wall, "temperature": VLM_TEMPERATURE,')
out = sub1(out, '            "category": category, "gold": expected, "answer": ans[:200]}',
           '            "category": category, "gold": expected, "answer": ans}')
out = sub1(out, '            elif arm == "vlm-swarm" and taskid in VLM_TASKS:\n                row.update(run_vlm_cell(model, taskid))',
           '            elif arm == "%s" and taskid in VLM_TASKS:\n                row.update(run_vlm_cell(model, taskid, seed))' % ARM)
out = sub1(out, '                result = run_vlm_cell(model, "n_number")', '                result = run_vlm_cell(model, "n_number", seed)')
out = sub1(out, '"""Fellowship gauntlet payload (v2)',
           '"""GENERATED by gen_vlm_hard_payload.py from map_vlm_swarm.py - do not edit; regenerate.\n'
           'Hard Bench vlm payload: arm `%s`, %d rendered cells (hard_vlm_tasks.py), sampled at --temp %s with the\n'
           'item seed. Frozen original docstring follows.\n\nFellowship gauntlet payload (v2)' % (ARM, len(hard_vlm_tasks.TASKS), TEMP))
DST.write_text(out, encoding="utf-8", newline="\n")
py_compile.compile(str(DST), doraise=True)
print("wrote", DST.name, "sha", hashlib.sha256(out.encode()).hexdigest()[:16], "| tasks", len(hard_vlm_tasks.TASKS), "| temp", TEMP)

# ---- positive control through the payload's OWN code path (sh + staging stubbed)
spec = importlib.util.spec_from_file_location("vlm_hard_payload", DST)
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)
assert set(mod.VLM_TASKS) == set(hard_vlm_tasks.TASKS) and "n_number" not in mod.VLM_TASKS
assert mod.VLM_TEMPERATURE == TEMP
hard_vlm_tasks.selftest(tempfile.mkdtemp(), score=mod._vlm_score)
print("answer-boundary copies agree with cli_answer on %d real cases" % payload_embed.check(mod))

calls = []
reply = {"text": ""}


def fake_sh(cmd, timeout):
    calls.append(cmd)
    return subprocess.CompletedProcess(cmd, 0, reply["text"].encode(), b"encoding done in 900 ms\n 7.5 tokens per second")


mod.sh = fake_sh
mod.stage_vlm_bundle = lambda model, taskid: ("/m.gguf", "/mm.gguf", "/img/" + mod._VLM_ALL[taskid][0], None)
MODEL = "SmolVLM2-500M-Video-Instruct-Q8_0"
fails = []
for tid, (_img, _q, gold, _match, _cat) in hard_vlm_tasks.TASKS.items():
    reply["text"] = gold.upper() + "\n"
    r = mod.run_vlm_cell(MODEL, tid, 4)
    if not (r["ok"] and "--temp %s --seed 4 " % TEMP in calls[-1] and r["temperature"] == TEMP):
        fails.append((tid, "gold", r, calls[-1][-80:]))
    reply["text"] = hard_vlm_tasks.WRONG[tid] + "\n"
    if mod.run_vlm_cell(MODEL, tid, 4)["ok"]:
        fails.append((tid, "wrong answer scored ok"))

reply["text"] = "\n\n  \n"
r = mod.run_vlm_cell(MODEL, "h_arrow", 1)
if r.get("ran") is not False or r.get("reason") != "answer_boundary:empty_stdout":
    fails.append(("empty stdout", "not reported as an instrument failure: %r" % r))
reply["text"] = "\n Left.\nThe arrow points to the left side.\n\n"
r = mod.run_vlm_cell(MODEL, "h_arrow", 1)
if r.get("answer") != "Left.\nThe arrow points to the left side." or not r.get("ok"):
    fails.append(("multi-line answer", "not kept whole: %r" % r.get("answer")))

work = tempfile.mkdtemp()
items = ["A~%s~%s~vlm~h_arrow~2~3" % (ARM, MODEL),
         "control~%s~vlm~control_vlm~0~1" % MODEL,
         "A~%s~%s~vlm~h_arrow~2~2" % (ARM, MODEL),          # seed != replicate + 1
         "A~vlm-swarm~%s~vlm~h_arrow~0~1" % MODEL,           # the frozen arm name must not run here
         "A~%s~%s~vlm~n_number~0~1" % (ARM, MODEL)]          # the control cell is not an experiment task
open(os.path.join(work, "items.txt"), "w").write("\n".join(items))
reply["text"] = "left\n"
calls.clear()
mod.main_rows = None
sys_argv = sys.argv
sys.argv = ["x", os.path.join(work, "items.txt"), os.path.join(work, "out.json")]
reply_map = {"h_arrow": "left\n", "n_number.png": "42\n"}
orig = fake_sh


def fake_sh2(cmd, timeout):
    reply["text"] = "42\n" if "n_number.png" in cmd else "left\n"
    return orig(cmd, timeout)


mod.sh = fake_sh2
mod.main()
sys.argv = sys_argv
rows = json.load(open(os.path.join(work, "out.json")))
got = [(r.get("ok"), r.get("reason"), r.get("control_result")) for r in rows]
want = [(True, None, None), (True, None, "VLM_CONTROL_PASS"), (False, "bad-replicate-seed", None),
        (False, "unknown-cell", None), (False, "unknown-cell", None)]
if got != want:
    fails.append(("main", got))
if not any("--seed 3 " in c for c in calls):
    fails.append(("main", "item seed 3 never reached the command"))
print("payload path controls: %d/%d tasks clean, main() %s" % (
    len(hard_vlm_tasks.TASKS) - len({f[0] for f in fails if f[0] != "main"}), len(hard_vlm_tasks.TASKS),
    "ok" if not any(f[0] == "main" for f in fails) else "FAILED"))
for f in fails:
    print("  FAIL", f)
assert not fails
