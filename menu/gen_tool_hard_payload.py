"""Generate map_tool_swarm_hard.py from the frozen map_tool_swarm.py: same staging, runtime, sampling
(--temp 0.6, seed = replicate + 1 - the tool payload already had the knob), scorer and row contract; changes
are the tool set (PREAMBLE + the GBNF tool-name rule, both from hard_tool_tasks.TOOLS), the task pool and the
experiment arm `tool-hard`. The frozen payload is never edited (Phase 5 manifests pin its sha).

GBNF and PREAMBLE are written with repr() of their RUNTIME text, so no backslash is hand-escaped in source;
the check below compares the imported payload's runtime strings against the intended ones byte for byte.
Positive control: every gold call through the generated payload's own score_tool, and process_item driven
with the llama call stubbed, so the prompt the tablet would see is the one asserted here.
    python gen_tool_hard_payload.py
"""
import hashlib, importlib.util, json, os, pathlib, pprint, py_compile, re, sys, tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import hard_tool_tasks as H  # noqa: E402
import menu_paths as MP  # noqa: E402  the payload folder and the mirrors are settings
import task_versions as TV  # noqa: E402  which generation of a template is current

SRC = pathlib.Path(MP.need("PAYLOADS")) / TV.newest_payload("map_tool_swarm.py")
_opt = lambda k, d=None: sys.argv[sys.argv.index(k) + 1] if k in sys.argv else d
# --model <gguf basename> --suffix <sfx> [--reasoning off]: the same pool on another tablet model
# (map_tool_swarm_hard<sfx>.py), the coding generator's pattern. The item contract refuses any other model name.
MODEL, SUFFIX, REASONING = _opt("--model"), _opt("--suffix", ""), _opt("--reasoning")
assert not (MODEL or REASONING) or SUFFIX, "--model/--reasoning need their own --suffix (one payload file per setting)"
# --out PATH writes elsewhere (a dry run while an order is using the live file - never swap a payload under it)
DST = pathlib.Path(_opt("--out") or pathlib.Path(MP.need("PAYLOADS")) / ("map_tool_swarm_hard%s.py" % SUFFIX))
ARM = "tool-hard"


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def sub1(text, old, new):
    assert text.count(old) == 1, "expected exactly one %r, found %d" % (old[:60], text.count(old))
    return text.replace(old, new, 1)


frozen = load(SRC, "tool_frozen")
g_lines = frozen.GBNF.split("\n")
idx = [i for i, l in enumerate(g_lines) if l.startswith("toolname ::= ")]
assert len(idx) == 1, idx
g_lines[idx[0]] = H.GBNF_TOOLNAME
GBNF_NEW = "\n".join(g_lines)

src = SRC.read_text(encoding="utf-8")
assert "\r" not in src
m = re.search(r"^GBNF = '''.*?'''\n", src, re.S | re.M)
assert m, "GBNF block not found"
src = src[:m.start()] + "GBNF = %r\n" % GBNF_NEW + src[m.end():]
m = re.search(r"^PREAMBLE = \(\n.*?^\)\n", src, re.S | re.M)
assert m, "PREAMBLE block not found"
src = src[:m.start()] + "PREAMBLE = %r\n" % H.PREAMBLE + src[m.end():]
m = re.search(r"^TASKS = \{\n.*?^\}\n", src, re.S | re.M)
assert m, "TASKS block not found"
src = src[:m.start()] + "TASKS = " + pprint.pformat(H.TASKS, width=150, sort_dicts=False) + "\n" + src[m.end():]
src = sub1(src, 'ARM_EXPERIMENT = "tool-swarm"', 'ARM_EXPERIMENT = "%s"' % ARM)
if MODEL:
    src = sub1(src, 'MODEL_NAME_FIXED = "%s"' % frozen.MODEL_NAME_FIXED, 'MODEL_NAME_FIXED = "%s"' % MODEL)
if REASONING is not None:
    assert REASONING in ("on", "off", "auto"), REASONING
    src = sub1(src, '        "-st", "--no-display-prompt",\n',
               '        "-st", "--no-display-prompt", "-rea", "%s",\n' % REASONING)
# The answer is cut at the measured boundary (cli_answer.py) and stored WHOLE. An unrecognised output shape is
# an instrument failure (error "answer_boundary:..."), never a model failure, and keeps the raw stdout.
import payload_embed  # noqa: E402
src = payload_embed.embed(src, "\ndef process_item(")
src = sub1(src, '    answer = isolate(stdout, prompt)\n',
           '    answer, aerr = llama_cli_answer(stdout, prompt)\n'
           '    if aerr:\n'
           '        row = _fail_row(item, arm, task, replicate, seed, model, aerr, wall=wall)\n'
           '        row["raw_stdout"] = _redact_sentinel(stdout)\n'
           '        return row\n')
src = sub1(src, '    row["answer"] = _redact_sentinel(answer[:400])\n', '    row["answer"] = _redact_sentinel(answer)\n')
src = sub1(src, '"""map_tool_swarm.py', '"""GENERATED by gen_tool_hard_payload.py from map_tool_swarm.py - do not edit; regenerate.\n'
           'Hard Bench tool payload: arm `%s`, %d tasks, %d tools (hard_tool_tasks.py). Frozen original docstring follows.\n\n'
           'map_tool_swarm.py' % (ARM, len(H.TASKS), len(H.TOOLS)))
DST.write_text(src, encoding="utf-8", newline="\n")
py_compile.compile(str(DST), doraise=True)
print("wrote", DST.name, "sha", hashlib.sha256(src.encode()).hexdigest()[:16], "| tasks", len(H.TASKS), "| tools", len(H.TOOLS))

mod = load(DST, "tool_hard")
# bytes, not parseability: the runtime strings are exactly the intended ones, and only the tool rule changed
assert mod.GBNF == GBNF_NEW and mod.PREAMBLE == H.PREAMBLE
assert [l for l in mod.GBNF.split("\n") if not l.startswith("toolname")] == \
       [l for l in frozen.GBNF.split("\n") if not l.startswith("toolname")]
assert '"\\"search_log\\""' in mod.GBNF and "\\\\" not in mod.GBNF.split("\n")[idx[0]]
assert mod.ARM_EXPERIMENT == ARM and set(mod.TASKS) == set(H.TASKS) and mod.EXPERIMENT_TASK_NAMES == tuple(H.TASKS)
assert mod.TEMPERATURE == frozen.TEMPERATURE and mod.MODEL_NAME_FIXED == (MODEL or frozen.MODEL_NAME_FIXED)
H.selftest(mod.score_tool)

# control cell still valid in the new tool set; drive process_item with the llama call stubbed
ct = mod.CONTROL_TASKS["control_tool"]
assert ct["gold_tool"] in H.TOOL_NAMES and ct["req"] == H.CONTROL_REQ
seen = {}


import test_cli_answer as _T  # noqa: E402
_REAL = next(x for x in _T.rows("probe-cli-multiline.20260927-193433") if x["item"].startswith("probe~toolml"))["stdout"]
BANNER = _REAL[:_REAL.index("\n> ")]                          # real spinner + banner + help block
STATS = _REAL[_REAL.rindex(payload_embed.cli_answer.LLAMA_CLI_STATS):]   # real stats line + Exiting
print("answer-boundary copies agree with cli_answer on %d real cases" % payload_embed.check(mod))


def real_shape(prompt, answer):
    lim = payload_embed.cli_answer.LLAMA_CLI_ECHO_LIMIT
    echo = prompt[:lim] + (payload_embed.cli_answer.LLAMA_CLI_TRUNCATED if len(prompt) > lim else "\n")
    return BANNER + "\n> " + echo + answer + STATS


def fake_llama(model, prompt, seed, prompt_path, grammar_path):
    seen["prompt"], seen["seed"] = prompt, seed
    t = mod.TASKS.get(seen.get("task")) or ct
    ans = json.dumps({"tool": t["gold_tool"], "arguments": t["gold_args"] or {}}, indent=2)
    return (real_shape(prompt, ans) if not seen.get("break") else BANNER + ans), 1.0, None


for name in ("check_arch", "check_ram", "ensure_llm_dir", "check_disk"):
    setattr(mod, name, lambda: None)
mod.stage_model = lambda model: ("/m.gguf", None)
mod.run_llama_with_grammar = fake_llama
work = tempfile.mkdtemp()
fails = []
for task in ("scale_double", "nofit_deploy", "update_paid"):
    seen["task"] = task
    item = "arm=%s;task=%s;replicate=2;seed=3;model=%s" % (ARM, task, mod.MODEL_NAME_FIXED)
    row = mod.process_item(item, os.path.join(work, "p"), os.path.join(work, "g"), work)
    if not (row["ok"] and seen["seed"] == 3 and mod.TASKS[task]["req"] in seen["prompt"]
            and "update_record(table, id, status)" in seen["prompt"]
            and json.loads(row["answer"])["tool"] == mod.TASKS[task]["gold_tool"]):
        fails.append((task, row))
seen["task"] = None
row = mod.process_item("arm=control;task=control_tool;replicate=0;seed=1;model=%s" % mod.MODEL_NAME_FIXED,
                       os.path.join(work, "p"), os.path.join(work, "g"), work)
if not row["ok"]:
    fails.append(("control", row))
seen["task"], seen["break"] = "update_paid", True           # no stats line: an instrument failure, not a model one
row = mod.process_item("arm=%s;task=update_paid;replicate=0;seed=1;model=%s" % (ARM, mod.MODEL_NAME_FIXED),
                       os.path.join(work, "p"), os.path.join(work, "g"), work)
if row["ok"] or row["error"] != "answer_boundary:stats_line_missing" or not row.get("raw_stdout"):
    fails.append(("boundary failure not reported as such", row["error"]))
seen["break"] = False
row = mod.process_item("arm=tool-swarm;task=scale_double;replicate=0;seed=1;model=%s" % mod.MODEL_NAME_FIXED,
                       os.path.join(work, "p"), os.path.join(work, "g"), work)
if row["ok"] or not row["error"].startswith("bad_item"):
    fails.append(("frozen arm accepted", row))
print("payload path controls:", "ok" if not fails else "FAILED")
for f in fails:
    print("  FAIL", f)
assert not fails
